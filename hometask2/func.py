        mas = s.split('.')
        for i in range(len(mas)):
            for x in mas[i]:
                if not(x.isalpha()):
                    mas[i] = mas[i].replace(x, ' ', 1)
            mas[i] = mas[i].replace('  ', ' ').replace('  ', ' ')
            mas[i] = mas[i].strip()
            mas[i] = mas[i].capitalize()
        s = '. '.join(mas)
        return s

