def level2():
    test1 = 'Ботать это круто. Очень круто'
    print('\nДобро пожаловать на уровень 2. Данный уровень предоставляет 3 метода изменения строки:\n'
          '1) {строка}.find() - возвращает первое вхождение выбранной подстроки в данной изначально строке;\n'
          '2) {строка}.replace() - заменяет выбранное слово(или подстроку) на новое введённое в изначальной строке;\n'
          '3) {строка}.count() - возвращает кол-во выбранных подстрок(символов) в изначальной строке.')
    print('\nПросто тесто))):\n'
          f'Тестовая строка: {test1}\n'
          f'Функция .find() (Найдём позицию первого вхождения слова "круто") - {test1.find('круто')}\n'
          f'Функция .replace() (Заменим слово круто на символ "@") - {test1.replace('круто', '@')}\n'
          f'Функция .count()  (Посчитаем кол-во букв "о")- {test1.count('о')}\n')
    print('А теперь введи свою строку в формате: "{номер функции}; {твоя строка}"')
    inp = input().split('; ')
    if inp[0] == '1':
        s = input('Введи слово, первое вхождение которого будем искать (если такого слова нет выведется -1): ')
        print(f'Первое вхождение слова "{s}" - {inp[1].find(s)}')
    elif inp[0] == '2':
        s = input('Введи сначала слово, которое меняем, а затем через ; слово/символ, на который меняем: ')
        print(f'Строка после изменений: {inp[1].replace(s.split('; ')[0], s.split('; ')[1])}')
    elif inp[0] == '3':
        s = input('Введи букву/слово, кол-во которой хочешь посчитать: ')
        print(f'Кол-во букв/слов "{s}" - {inp[1].count(s)}')

